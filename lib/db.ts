// SuiteScout Postgres layer — shared platform-postgres.
// `pg` (node-postgres) against DATABASE_URL, which is REQUIRED: the
// app fails fast with a clear message when it is unset. Schema is
// created on first use and the 20 batch-3 prospects are seeded when
// the table is empty. No SQLite anywhere in this file.
import { Pool, type PoolClient } from "pg";
import { seedProspects, type SeedProspect } from "./seed";
