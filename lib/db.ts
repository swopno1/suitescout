export async function updateDiscount(
  id: number,
  patch: Partial<
    Pick<
      Discount,
      | "state"
      | "approved_by"
      | "stripe_coupon_id"
      | "stripe_subscription_id"
      | "last_error"
    >
  > & {
    approved_at?: string | null;
    applied_at?: string | null;
    consumed_at?: string | null;
  },
): Promise<Discount | null> {
  const pool = await db();
  const sets: string[] = ["updated_at = NOW()"];
  const params: unknown[] = [];
  const push = (col: string, v: unknown) => {
    params.push(v);
    sets.push(`${col} = $${params.length}`);
  };
  if (patch.state !== undefined) push("state", patch.state);
  if (patch.approved_by !== undefined) push("approved_by", patch.approved_by);
  if (patch.approved_at !== undefined) push("approved_at", patch.approved_at);
  if (patch.applied_at !== undefined) push("applied_at", patch.applied_at);
  if (patch.consumed_at !== undefined) push("consumed_at", patch.consumed_at);
  if (patch.stripe_coupon_id !== undefined) {
    push("stripe_coupon_id", patch.stripe_coupon_id);
  }
  if (patch.stripe_subscription_id !== undefined) {
    push("stripe_subscription_id", patch.stripe_subscription_id);
  }
  if (patch.last_error !== undefined) push("last_error", patch.last_error);
  params.push(id);
  const res = await pool.query(
    `UPDATE discounts SET ${sets.join(", ")} WHERE id = $${params.length} RETURNING *`,
    params,
  );
  const row = res.rows[0] as DiscountRow | undefined;
  return row ? mapDiscount(row) : null;
}

export interface DataCounts {
  prospects: number;
  runs: number;
  drafts: number;
  followups: number;
  byStatus: Record<string, number>;
  byBand: Record<string, number>;
  bySource: Record<string, number>;
}

/** Whole-database counts for the settings data card — one round trip
 *  per group, no row fetching. */
export async function getDataCounts(): Promise<DataCounts> {
  const pool = await db();
  const [totals, byStatus, byBand, bySource] = await Promise.all([
    pool.query(
      `SELECT (SELECT COUNT(*)::int FROM prospects) AS prospects,
              (SELECT COUNT(*)::int FROM runs) AS runs,
              (SELECT COUNT(*)::int FROM drafts) AS drafts,
              (SELECT COUNT(*)::int FROM followups) AS followups`,
    ),
    pool.query(
      "SELECT status AS k, COUNT(*)::int AS n FROM prospects GROUP BY status",
    ),
    pool.query(
      `SELECT COALESCE(score_band, 'unscored') AS k, COUNT(*)::int AS n
       FROM prospects GROUP BY score_band`,
    ),
    pool.query(
      "SELECT source AS k, COUNT(*)::int AS n FROM prospects GROUP BY source",
    ),
  ]);
  const asRecord = (rows: { k: string; n: number }[]) =>
    Object.fromEntries(rows.map((r) => [r.k, r.n]));
  const t = totals.rows[0] as {
    prospects: number;
    runs: number;
    drafts: number;
    followups: number;
  };
  return {
    prospects: t.prospects,
    runs: t.runs,
    drafts: t.drafts,
    followups: t.followups,
    byStatus: asRecord(byStatus.rows as { k: string; n: number }[]),
    byBand: asRecord(byBand.rows as { k: string; n: number }[]),
    bySource: asRecord(bySource.rows as { k: string; n: number }[]),
  };
}

