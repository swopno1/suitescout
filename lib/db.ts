/** Persist a run's step trace / status. The agent calls this after
 *  every step so the run view polls live progress. */
export async function updateRun(
  id: number,
  patch: { steps?: RunStep[]; status?: Run["status"] },
): Promise<Run | null> {
  const pool = await db();
  const current = await getRun(id);
  if (!current) return null;
  const steps = patch.steps ?? current.steps;
  const status = patch.status ?? current.status;
  const finishedAt =
    status === "done" || status === "failed"
      ? (current.finished_at ?? new Date().toISOString())
      : current.finished_at;
  await pool.query(
    "UPDATE runs SET steps = $1, status = $2, finished_at = $3 WHERE id = $4",
    [JSON.stringify(steps), status, finishedAt, id],
  );
  return getRun(id);
}

