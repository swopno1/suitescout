export async function updateScout(
  id: number,
  patch: Partial<
    Pick<
      Scout,
      | "display_name"
      | "south"
      | "west"
      | "north"
      | "east"
      | "status"
      | "phase"
      | "found"
      | "junk_skipped"
      | "dupes_skipped"
      | "imported"
      | "error"
      | "finished_at"
    >
  > & { prospect_ids?: number[] },
): Promise<Scout | null> {
  const pool = await db();
  const sets: string[] = [];
  const params: unknown[] = [];
  const push = (col: string, v: unknown) => {
    params.push(v);
    sets.push(`${col} = $${params.length}`);
  };
  if (patch.display_name !== undefined) push("display_name", patch.display_name);
  if (patch.south !== undefined) push("south", patch.south);
  if (patch.west !== undefined) push("west", patch.west);
  if (patch.north !== undefined) push("north", patch.north);
  if (patch.east !== undefined) push("east", patch.east);
  if (patch.status !== undefined) push("status", patch.status);
  if (patch.phase !== undefined) push("phase", patch.phase);
  if (patch.found !== undefined) push("found", patch.found);
  if (patch.junk_skipped !== undefined) push("junk_skipped", patch.junk_skipped);
  if (patch.dupes_skipped !== undefined) push("dupes_skipped", patch.dupes_skipped);
  if (patch.imported !== undefined) push("imported", patch.imported);
  if (patch.prospect_ids !== undefined) {
    push("prospect_ids", JSON.stringify(patch.prospect_ids));
  }
  if (patch.error !== undefined) push("error", patch.error);
  if (patch.finished_at !== undefined) push("finished_at", patch.finished_at);
  if (sets.length === 0) return getScout(id);
  await pool.query(`UPDATE scouts SET ${sets.join(", ")} WHERE id = $${params.length + 1}`, [
    ...params,
    id,
  ]);
  return getScout(id);
}

