export async function approveDraft(id: number): Promise<Draft | null> {
  const pool = await db();
  const draft = await getDraft(id);
  if (!draft) return null;
  if (draft.status !== "draft") return draft;
  await pool.query("UPDATE drafts SET status = 'approved' WHERE id = $1", [
    id,
  ]);
  return getDraft(id);
}

