// ---- Prospects ----

export async function listProspects(filters?: {
  status?: string;
  band?: string;
}): Promise<Prospect[]> {
  const pool = await db();
  const where: string[] = [];
  const params: unknown[] = [];
  if (filters?.status) {
    params.push(filters.status);
    where.push(`status = $${params.length}`);
  }
  if (filters?.band) {
    params.push(filters.band);
    where.push(`score_band = $${params.length}`);
  }
  const sql =
    "SELECT * FROM prospects" +
    (where.length ? ` WHERE ${where.join(" AND ")}` : "") +
    " ORDER BY demo DESC, name ASC";
  const res = await pool.query(sql, params);
  return (res.rows as ProspectRow[]).map(mapProspect);
}

export async function getProspect(id: number): Promise<Prospect | null> {
  const pool = await db();
  const res = await pool.query("SELECT * FROM prospects WHERE id = $1", [
    id,
  ]);
  const row = res.rows[0] as ProspectRow | undefined;
  return row ? mapProspect(row) : null;
}

export async function createProspect(input: {
  name: string;
  website?: string | null;
  location?: string | null;
  /** Defaults to manual; area scouting passes osm. */
  source?: string;
  /** Listed-contact JSON (see lib/geo.serializeListedContact). */
  contact?: string | null;
}): Promise<Prospect> {
  const pool = await db();
  const now = new Date().toISOString();
  const res = await pool.query(
    `INSERT INTO prospects
      (name, website, location, source, contact, status, demo, created_at, updated_at)
     VALUES ($1, $2, $3, $4, $5, 'new', FALSE, $6, $7)
     RETURNING id`,
    [
      input.name.trim(),
      input.website?.trim() || null,
      input.location?.trim() || null,
      input.source?.trim() || "manual",
      input.contact ?? null,
      now,
      now,
    ],
  );
  const created = await getProspect((res.rows[0] as { id: number }).id);
  if (!created) throw new Error("Failed to create prospect");
  await pool.query(
    `INSERT INTO prospect_status_events (prospect_id, from_status, to_status, created_at)
     VALUES ($1, NULL, 'new', $2)`,
    [created.id, now],
  );
  return created;
}

export async function updateProspectStatus(
  id: number,
  status: ProspectStatus,
): Promise<Prospect | null> {
  const pool = await db();
  const previous = await getProspect(id);
  if (!previous) return null;
  if (previous.status === status) return previous;
  const now = new Date().toISOString();
  await pool.query(
    "UPDATE prospects SET status = $1, updated_at = $2 WHERE id = $3",
    [status, now, id],
  );
  await pool.query(
    `INSERT INTO prospect_status_events (prospect_id, from_status, to_status, created_at)
     VALUES ($1, $2, $3, $4)`,
    [id, previous.status, status, now],
  );
  return getProspect(id);
}

