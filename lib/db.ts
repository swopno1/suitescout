// ---- Follow-ups ----

export async function listPendingFollowups(limit = 10): Promise<(Followup & { prospect_name: string })[]> {
  const pool = await db();
  const res = await pool.query(
    `SELECT f.*, p.name AS prospect_name FROM followups f
     JOIN prospects p ON p.id = f.prospect_id
     WHERE f.status = 'pending' ORDER BY f.created_at ASC LIMIT $1`,
    [limit],
  );
  return res.rows as (Followup & { prospect_name: string })[];
}

export async function listFollowupsForProspect(
  prospectId: number,
): Promise<Followup[]> {
  const pool = await db();
  const res = await pool.query(
    "SELECT * FROM followups WHERE prospect_id = $1 ORDER BY id DESC",
    [prospectId],
  );
  return (res.rows as FollowupRow[]).map(mapFollowup);
}

export async function createFollowup(input: {
  prospectId: number;
  draftId: number | null;
  dueAfterDays: number;
}): Promise<Followup> {
  const pool = await db();
  const now = new Date().toISOString();
  const res = await pool.query(
    `INSERT INTO followups (prospect_id, draft_id, due_after_days, status, created_at)
     VALUES ($1, $2, $3, 'pending', $4)
     RETURNING id`,
    [input.prospectId, input.draftId, input.dueAfterDays, now],
  );
  const created = await pool.query(
    "SELECT * FROM followups WHERE id = $1",
    [(res.rows[0] as { id: number }).id],
  );
  const row = created.rows[0] as FollowupRow | undefined;
  if (!row) throw new Error("Failed to create follow-up");
  return mapFollowup(row);
}

