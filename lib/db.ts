const DATABASE_URL_ERROR =
  "DATABASE_URL is required — set it to the PostgreSQL connection string " +
  "(see .env.example). The app has no local database fallback.";

function requireDatabaseUrl(): string {
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error(DATABASE_URL_ERROR);
  return url;
}

/** Postgres DDL for the five tables. Idempotent: CREATE TABLE IF NOT
 *  EXISTS. ids are GENERATED BY DEFAULT AS IDENTITY (not ALWAYS) so
 *  the SQLite→Postgres migration can preserve existing ids, and so a
 *  fresh deploy can re-seed without fighting the sequence. Also
 *  imported by scripts/migrate-sqlite-to-postgres.ts. */
export const SCHEMA_SQL = `
  CREATE TABLE IF NOT EXISTS prospects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    website TEXT,
    location TEXT,
    source TEXT NOT NULL DEFAULT 'manual',
    contact TEXT,
    research_sources TEXT,
    status TEXT NOT NULL DEFAULT 'new',
    fit_score INTEGER,
    score_band TEXT,
    score_reasons TEXT,
    research TEXT,
    demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
  );
  CREATE TABLE IF NOT EXISTS runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prospect_id INTEGER NOT NULL REFERENCES prospects(id),
    steps TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'queued',
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ
  );
  CREATE TABLE IF NOT EXISTS drafts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prospect_id INTEGER NOT NULL REFERENCES prospects(id),
    channel TEXT NOT NULL,
    subject TEXT,
    body TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'draft',
    created_at TIMESTAMPTZ NOT NULL,
    approved_at TIMESTAMPTZ,
    sent_at TIMESTAMPTZ
  );
  CREATE TABLE IF NOT EXISTS followups (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prospect_id INTEGER NOT NULL REFERENCES prospects(id),
    draft_id INTEGER REFERENCES drafts(id),
    due_after_days INTEGER NOT NULL DEFAULT 3,
    status TEXT NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL
  );
  CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS prospect_status_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prospect_id INTEGER NOT NULL REFERENCES prospects(id),
    from_status TEXT,
    to_status TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
  );
  CREATE INDEX IF NOT EXISTS prospect_status_events_prospect_idx
    ON prospect_status_events (prospect_id);
  CREATE TABLE IF NOT EXISTS sends (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prospect_id INTEGER REFERENCES prospects(id),
    draft_id INTEGER REFERENCES drafts(id),
    channel TEXT NOT NULL,
    to_email TEXT NOT NULL,
    resend_id TEXT,
    auto BOOLEAN NOT NULL DEFAULT FALSE,
    status TEXT NOT NULL DEFAULT 'sent',
    error TEXT,
    created_at TIMESTAMPTZ NOT NULL
  );
  CREATE INDEX IF NOT EXISTS sends_created_idx ON sends (created_at);
  CREATE INDEX IF NOT EXISTS sends_draft_idx ON sends (draft_id);
`;

declare global {
  // eslint-disable-next-line no-var
  var __suitescoutPool: Pool | undefined;
  // eslint-disable-next-line no-var
  var __suitescoutReady: Promise<void> | null | undefined;
}

function getPool(): Pool {
  if (!globalThis.__suitescoutPool) {
    globalThis.__suitescoutPool = new Pool({
      connectionString: requireDatabaseUrl(),
      max: 5,
    });
  }
  return globalThis.__suitescoutPool;
}

/** Lightweight migrations for DBs created before a column/table
 *  existed. Each step checks first — safe to run on every boot. */
async function migrate(client: PoolClient): Promise<void> {
  const hasColumn = async (table: string, column: string): Promise<boolean> => {
    const res = await client.query(
      `SELECT 1 FROM information_schema.columns
        WHERE table_name = $1 AND column_name = $2`,
      [table, column],
    );
    return (res.rowCount ?? 0) > 0;
  };
  if (!(await hasColumn("prospects", "research_sources"))) {
    await client.query(
      "ALTER TABLE prospects ADD COLUMN research_sources TEXT",
    );
  }
  if (!(await hasColumn("drafts", "approved_at"))) {
    await client.query("ALTER TABLE drafts ADD COLUMN approved_at TIMESTAMPTZ");
  }
  if (!(await hasColumn("drafts", "sent_at"))) {
    await client.query("ALTER TABLE drafts ADD COLUMN sent_at TIMESTAMPTZ");
  }
  if (!(await hasColumn("followups", "created_at"))) {
    await client.query(
      "ALTER TABLE followups ADD COLUMN created_at TIMESTAMPTZ",
    );
    // Backfill from the parent run (finished → started), else now.
    await client.query(
      `UPDATE followups f SET created_at = COALESCE(
         (SELECT r.finished_at FROM runs r
           WHERE r.prospect_id = f.prospect_id AND r.finished_at IS NOT NULL
           ORDER BY r.id DESC LIMIT 1),
         (SELECT r.started_at FROM runs r
           WHERE r.prospect_id = f.prospect_id
           ORDER BY r.id DESC LIMIT 1),
         NOW()
       ) WHERE created_at IS NULL`,
    );
    await client.query(
      "ALTER TABLE followups ALTER COLUMN created_at SET NOT NULL",
    );
  }
  // Status-event history (table is in SCHEMA_SQL for fresh DBs).
  await client.query(
    `INSERT INTO prospect_status_events (prospect_id, from_status, to_status, created_at)
     SELECT p.id, NULL, p.status, p.created_at FROM prospects p
     WHERE NOT EXISTS (
       SELECT 1 FROM prospect_status_events e WHERE e.prospect_id = p.id
     )`,
  );
}

async function seedIfEmpty(client: PoolClient): Promise<void> {
  const res = await client.query("SELECT COUNT(*)::int AS n FROM prospects");
  if ((res.rows[0] as { n: number }).n > 0) return;
  const rows: { p: SeedProspect; now: string }[] = [];
  seedProspects((p, now) => {
    rows.push({ p, now });
  });
  for (const { p, now } of rows) {
    await client.query(
      `INSERT INTO prospects
        (name, website, location, source, contact, research_sources, status, demo, created_at, updated_at)
       VALUES ($1, $2, $3, 'batch3', NULL, $4, 'new', $5, $6, $7)`,
      [
        p.name,
        p.website,
        p.location,
        p.sources ? JSON.stringify(p.sources) : null,
        p.demo,
        now,
        now,
      ],
    );
  }
}

/** First-boot init: schema + migrate + seed, in one transaction,
 *  serialized with an advisory lock so concurrent first requests
 *  cannot double-seed. */
async function ensureDb(): Promise<void> {
  const pool = getPool();
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    // Serialize first-boot init across concurrent requests.
    await client.query("SELECT pg_advisory_xact_lock(727271)");
    await client.query(SCHEMA_SQL);
    await migrate(client);
    await seedIfEmpty(client);
    await client.query("COMMIT");
  } catch (err) {
    await client.query("ROLLBACK").catch(() => undefined);
    throw err;
  } finally {
    client.release();
  }
}

/** First use: pool + schema + seed. A failed init is cleared so the
 *  next call retries instead of poisoning every later request. */
async function db(): Promise<Pool> {
  if (!globalThis.__suitescoutReady) {
    globalThis.__suitescoutReady = ensureDb().catch((err: unknown) => {
      globalThis.__suitescoutReady = null;
      throw err;
    });
  }
  await globalThis.__suitescoutReady;
  return getPool();
}

