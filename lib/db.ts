// SuiteScout Postgres layer — shared platform-postgres.
// `pg` (node-postgres) against DATABASE_URL, which is REQUIRED: the
// app fails fast with a clear message when it is unset. Schema is
// created on first use and the 20 batch-3 prospects are seeded when
// the table is empty. No SQLite anywhere in this file.
import { Pool, type PoolClient } from "pg";
import { seedProspects, type SeedProspect } from "./seed";
import type {
  Draft,
  Followup,
  Prospect,
  ProspectStatus,
  Run,
  RunStep,
  ScoreBand,
} from "./types";

const DATABASE_URL_ERROR =
  "DATABASE_URL is required — set it to the PostgreSQL connection string " +
  "(see .env.example). The app has no local database fallback.";

function requireDatabaseUrl(): string {
  const url = process.env.DATABASE_URL;
  if (!url) throw new Error(DATABASE_URL_ERROR);
  return url;
}

/** Postgres DDL for the five tables. Idempotent: CREATE TABLE IF NOT
 *  EXISTS. ids are GENERATED BY DEFAULT AS IDENTITY (not ALWAYS) so
 *  the SQLite→Postgres migration can preserve existing ids, and so a
 *  fresh deploy can re-seed without fighting the sequence. Also
 *  imported by scripts/migrate-sqlite-to-postgres.ts. */
export const SCHEMA_SQL = `
  CREATE TABLE IF NOT EXISTS prospects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    website TEXT,
    location TEXT,
    source TEXT NOT NULL DEFAULT 'manual',
    contact TEXT,
    research_sources TEXT,
    status TEXT NOT NULL DEFAULT 'new',
    fit_score INTEGER,
    score_band TEXT,
    score_reasons TEXT,
    research TEXT,
    demo BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
  );
  CREATE TABLE IF NOT EXISTS runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prospect_id INTEGER NOT NULL REFERENCES prospects(id),
    steps TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'queued',
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ
  );
  CREATE TABLE IF NOT EXISTS drafts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prospect_id INTEGER NOT NULL REFERENCES prospects(id),
    channel TEXT NOT NULL,
    subject TEXT,
    body TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'draft',
    created_at TIMESTAMPTZ NOT NULL
  );
  CREATE TABLE IF NOT EXISTS followups (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prospect_id INTEGER NOT NULL REFERENCES prospects(id),
    draft_id INTEGER REFERENCES drafts(id),
    due_after_days INTEGER NOT NULL DEFAULT 3,
    status TEXT NOT NULL DEFAULT 'pending'
  );
  CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
  );
`;

declare global {
  // eslint-disable-next-line no-var
  var __suitescoutPool: Pool | undefined;
  // eslint-disable-next-line no-var
  var __suitescoutReady: Promise<void> | null | undefined;
}

function getPool(): Pool {
  if (!globalThis.__suitescoutPool) {
    globalThis.__suitescoutPool = new Pool({
      connectionString: requireDatabaseUrl(),
      max: 5,
    });
  }
  return globalThis.__suitescoutPool;
}

/** Lightweight migration for DBs created before a column existed.
 *  Adds `research_sources` to prospects when it is missing. */
async function migrate(client: PoolClient): Promise<void> {
  const res = await client.query(
    `SELECT 1 FROM information_schema.columns
      WHERE table_name = 'prospects' AND column_name = 'research_sources'`,
  );
  if ((res.rowCount ?? 0) === 0) {
    await client.query(
      "ALTER TABLE prospects ADD COLUMN research_sources TEXT",
    );
  }
}

async function seedIfEmpty(client: PoolClient): Promise<void> {
  const res = await client.query("SELECT COUNT(*)::int AS n FROM prospects");
  if ((res.rows[0] as { n: number }).n > 0) return;
  const rows: { p: SeedProspect; now: string }[] = [];
  seedProspects((p, now) => {
    rows.push({ p, now });
  });
  for (const { p, now } of rows) {
    await client.query(
      `INSERT INTO prospects
        (name, website, location, source, contact, research_sources, status, demo, created_at, updated_at)
       VALUES ($1, $2, $3, 'batch3', NULL, $4, 'new', $5, $6, $7)`,
      [
        p.name,
        p.website,
        p.location,
        p.sources ? JSON.stringify(p.sources) : null,
        p.demo,
        now,
        now,
      ],
    );
  }
}

/** First-boot init: schema + migrate + seed, in one transaction,
 *  serialized with an advisory lock so concurrent first requests
 *  cannot double-seed. */
async function ensureDb(): Promise<void> {
  const pool = getPool();
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    // Serialize first-boot init across concurrent requests.
    await client.query("SELECT pg_advisory_xact_lock(727271)");
    await client.query(SCHEMA_SQL);
    await migrate(client);
    await seedIfEmpty(client);
    await client.query("COMMIT");
  } catch (err) {
    await client.query("ROLLBACK").catch(() => undefined);
    throw err;
  } finally {
    client.release();
  }
}

/** First use: pool + schema + seed. A failed init is cleared so the
 *  next call retries instead of poisoning every later request. */
async function db(): Promise<Pool> {
  if (!globalThis.__suitescoutReady) {
    globalThis.__suitescoutReady = ensureDb().catch((err: unknown) => {
      globalThis.__suitescoutReady = null;
      throw err;
    });
  }
  await globalThis.__suitescoutReady;
  return getPool();
}

// ---- Row mapping (JSON columns are stored as TEXT; pg returns
// TIMESTAMPTZ as Date — the app works in ISO strings) ----

/** pg returns TIMESTAMPTZ as Date — the app works in ISO strings. */
function toIso(v: Date | string | null): string | null {
  if (v === null) return null;
  return v instanceof Date ? v.toISOString() : v;
}

interface ProspectRow {
  id: number;
  name: string;
  website: string | null;
  location: string | null;
  source: string;
  contact: string | null;
  research_sources: string | null;
  status: string;
  fit_score: number | null;
  score_band: string | null;
  score_reasons: string | null;
  research: string | null;
  demo: boolean;
  created_at: Date | string;
  updated_at: Date | string;
}

function mapProspect(row: ProspectRow): Prospect {
  return {
    id: row.id,
    name: row.name,
    website: row.website,
    location: row.location,
    source: row.source,
    contact: row.contact,
    research_sources: row.research_sources
      ? (JSON.parse(row.research_sources) as string[])
      : null,
    status: row.status as ProspectStatus,
    fit_score: row.fit_score,
    score_band: row.score_band as ScoreBand | null,
    score_reasons: row.score_reasons
      ? (JSON.parse(row.score_reasons) as string[])
      : null,
    research: row.research ? JSON.parse(row.research) : null,
    demo: row.demo,
    created_at: toIso(row.created_at) as string,
    updated_at: toIso(row.updated_at) as string,
  };
}

interface RunRow {
  id: number;
  prospect_id: number;
  steps: string;
  status: string;
  started_at: Date | string;
  finished_at: Date | string | null;
}

function mapRun(row: RunRow): Run {
  return {
    id: row.id,
    prospect_id: row.prospect_id,
    steps: JSON.parse(row.steps) as RunStep[],
    status: row.status as Run["status"],
    started_at: toIso(row.started_at) as string,
    finished_at: toIso(row.finished_at),
  };
}

interface DraftRow {
  id: number;
  prospect_id: number;
  channel: string;
  subject: string | null;
  body: string;
  status: string;
  created_at: Date | string;
}

function mapDraft(row: DraftRow): Draft {
  return {
    id: row.id,
    prospect_id: row.prospect_id,
    channel: row.channel as Draft["channel"],
    subject: row.subject,
    body: row.body,
    status: row.status as Draft["status"],
    created_at: toIso(row.created_at) as string,
  };
}

// ---- Prospects ----

export async function listProspects(filters?: {
  status?: string;
  band?: string;
}): Promise<Prospect[]> {
  const pool = await db();
  const where: string[] = [];
  const params: unknown[] = [];
  if (filters?.status) {
    params.push(filters.status);
    where.push(`status = $${params.length}`);
  }
  if (filters?.band) {
    params.push(filters.band);
    where.push(`score_band = $${params.length}`);
  }
  const sql =
    "SELECT * FROM prospects" +
    (where.length ? ` WHERE ${where.join(" AND ")}` : "") +
    " ORDER BY demo DESC, name ASC";
  const res = await pool.query(sql, params);
  return (res.rows as ProspectRow[]).map(mapProspect);
}

export async function getProspect(id: number): Promise<Prospect | null> {
  const pool = await db();
  const res = await pool.query("SELECT * FROM prospects WHERE id = $1", [
    id,
  ]);
  const row = res.rows[0] as ProspectRow | undefined;
  return row ? mapProspect(row) : null;
}

export async function createProspect(input: {
  name: string;
  website?: string | null;
  location?: string | null;
}): Promise<Prospect> {
  const pool = await db();
  const now = new Date().toISOString();
  const res = await pool.query(
    `INSERT INTO prospects
      (name, website, location, source, contact, status, demo, created_at, updated_at)
     VALUES ($1, $2, $3, 'manual', NULL, 'new', FALSE, $4, $5)
     RETURNING id`,
    [
      input.name.trim(),
      input.website?.trim() || null,
      input.location?.trim() || null,
      now,
      now,
    ],
  );
  const created = await getProspect((res.rows[0] as { id: number }).id);
  if (!created) throw new Error("Failed to create prospect");
  return created;
}

export async function updateProspectStatus(
  id: number,
  status: ProspectStatus,
): Promise<Prospect | null> {
  const pool = await db();
  const now = new Date().toISOString();
  const res = await pool.query(
    "UPDATE prospects SET status = $1, updated_at = $2 WHERE id = $3",
    [status, now, id],
  );
  if ((res.rowCount ?? 0) === 0) return null;
  return getProspect(id);
}

