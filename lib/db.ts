// ---- Runs ----

export async function createRun(
  prospectId: number,
  steps: RunStep[],
): Promise<Run> {
  const pool = await db();
  const now = new Date().toISOString();
  const res = await pool.query(
    `INSERT INTO runs (prospect_id, steps, status, started_at, finished_at)
     VALUES ($1, $2, 'queued', $3, NULL)
     RETURNING id`,
    [prospectId, JSON.stringify(steps), now],
  );
  const created = await getRun((res.rows[0] as { id: number }).id);
  if (!created) throw new Error("Failed to create run");
  return created;
}

export async function getRun(id: number): Promise<Run | null> {
  const pool = await db();
  const res = await pool.query("SELECT * FROM runs WHERE id = $1", [id]);
  const row = res.rows[0] as RunRow | undefined;
  return row ? mapRun(row) : null;
}

export async function getLatestRun(): Promise<Run | null> {
  const pool = await db();
  const res = await pool.query("SELECT * FROM runs ORDER BY id DESC LIMIT 1");
  const row = res.rows[0] as RunRow | undefined;
  return row ? mapRun(row) : null;
}

/** Persist a run's step trace / status. The agent calls this after
 *  every step so the run view polls live progress. */
export async function updateRun(
  id: number,
  patch: { steps?: RunStep[]; status?: Run["status"] },
): Promise<Run | null> {
  const pool = await db();
  const current = await getRun(id);
  if (!current) return null;
  const steps = patch.steps ?? current.steps;
  const status = patch.status ?? current.status;
  const finishedAt =
    status === "done" || status === "failed"
      ? (current.finished_at ?? new Date().toISOString())
      : current.finished_at;
  await pool.query(
    "UPDATE runs SET steps = $1, status = $2, finished_at = $3 WHERE id = $4",
    [JSON.stringify(steps), status, finishedAt, id],
  );
  return getRun(id);
}

export async function listRunsForProspect(
  prospectId: number,
): Promise<Run[]> {
  const pool = await db();
  const res = await pool.query(
    "SELECT * FROM runs WHERE prospect_id = $1 ORDER BY id DESC",
    [prospectId],
  );
  return (res.rows as RunRow[]).map(mapRun);
}

/** True when the prospect already has a queued or running run — the
 *  batch route skips those so a prospect never gets two live runs. */
export async function hasActiveRun(prospectId: number): Promise<boolean> {
  const pool = await db();
  const res = await pool.query(
    "SELECT COUNT(*)::int AS n FROM runs WHERE prospect_id = $1 AND status IN ('queued', 'running')",
    [prospectId],
  );
  return (res.rows[0] as { n: number }).n > 0;
}

